# ===== VALIDATION =====
def validate_prompts():
    """Проверка что все промпты валидные"""
    prompts = {
        "SYSTEM_PROMPT": SYSTEM_PROMPT,
        "GOAL_TIPS": GOAL_TIPS,
        "EXPLAIN_PRODUCT": EXPLAIN_PRODUCT,
        "ANALYZE_SPENDING": ANALYZE_SPENDING,
    }
    
    for name, prompt in prompts.items():
        if not prompt or len(prompt) < 50:
            print(f"⚠️ Warning: {name} is too short")
        else:
            print(f"✅ {name}: OK ({len(prompt)} chars)")


if __name__ == "__main__":
    validate_prompts()